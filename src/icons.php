/**
 * Line icons drawn in the text colour, so they follow the palette, light or
 * dark. The drawings are Free Form Certificate's, so the two plugins look
 * alike: 24×24, a stroke in `currentColor`, and only geometry, never a
 * colour, a style or a script of their own. The registry holds only the
 * icons this plugin draws; a new one is copied from Free Form Certificate's
 * `Core\Icons` (or drawn in the same way) and added here.
 *
 * Two ways in, one drawing, as in Free Form Certificate:
 *
 * - `svg()` prints it inline, for the settings screen's headings and tabs;
 * - the `.esg-icon-<name>` classes of {@see self::CLASSES} draw it as a CSS
 *   mask on `::before`, which is how the buttons get it, the form's buttons
 *   included (the script builds those, and the standalone HTML has no PHP).
 *   That CSS is generated by {@see self::stylesheet()} and committed into
 *   `assets/css/buttons.css` between markers; `ButtonsTest` fails when the
 *   two disagree. Regenerate with
 *   `ESG_UPDATE_ICON_CSS=1 vendor/bin/phpunit --filter ButtonsTest`.
 *
 * The class was `Admin\Icons` until the form's buttons needed it (#106).
 */
