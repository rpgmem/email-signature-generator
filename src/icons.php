	/**
	 * The icons drawn as `.esg-icon-<name>` classes: the ones a button
	 * carries. Only these reach the stylesheet, so the form's page does not
	 * download the drawings of the settings screen's headings.
	 *
	 * @var list<string>
	 */
	public const CLASSES = array( 'copy', 'download', 'edit', 'eraser', 'image', 'plus', 'restore', 'save', 'trash' );

	public const CSS_BEGIN = '/* esg-icons:begin — generated by EmailSignatureGenerator\Icons::stylesheet(); do not edit by hand. */';

	public const CSS_END = '/* esg-icons:end */';

	/**
	 * Whether an icon exists.
	 *
	 * @param string $name Icon name.
	 */
	public static function has( string $name ): bool {
		return isset( self::PATHS[ $name ] );
	}

	/**
	 * Every icon name.
	 *
	 * @return list<string>
	 */
	public static function names(): array {
		return array_keys( self::PATHS );
	}

	/**
	 * Whether an icon is drawn as a class, so a button can carry it.
	 *
	 * @param string $name Icon name.
	 */
	public static function isClass( string $name ): bool {
		return in_array( $name, self::CLASSES, true ) && self::has( $name );
	}

	/**
	 * The icon as inline SVG, hidden from assistive technology because the
	 * text beside it says the same; '' for an unknown name.
	 *
	 * @param string $name Icon name.
	 * @param int    $size Width and height in pixels.
	 */
	public static function svg( string $name, int $size = 20 ): string {
		if ( ! self::has( $name ) ) {
			return '';
		}
		return sprintf(
			'<svg class="esg-icon" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="%1$d" height="%1$d" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">%2$s</svg>',
			max( 1, $size ),
			self::PATHS[ $name ]
		);
	}

	/**
	 * The CSS that draws every `.esg-icon-*` class, between its markers.
	 *
	 * Each icon is a mask over `currentColor`, so it takes the text colour of
	 * its button, in either theme; it sits in `::before` with no content, so
	 * it stays out of the accessibility tree. Sizes are in `em`, so the icon
	 * scales with the label beside it. Under forced colours the mask's ground
	 * would be replaced by the system's and the icon would vanish, so there
	 * it is painted in the system text colour.
	 */
	public static function stylesheet(): string {
		$selectors = array();
		$rules     = array();
		foreach ( self::CLASSES as $name ) {
			$selector    = '.esg-icon-' . $name . '::before';
			$selectors[] = $selector;
			$url         = 'url("data:image/svg+xml,' . self::dataUriBody( $name ) . '")';
			$rules[]     = $selector . " {\n\t-webkit-mask-image: " . $url . ";\n\tmask-image: " . $url . ";\n}";
		}

		$base = implode( ",\n", $selectors ) . " {\n"
			. "\tcontent: \"\";\n"
			. "\tdisplay: inline-block;\n"
			. "\tflex-shrink: 0;\n"
			. "\twidth: 1.15em;\n"
			. "\theight: 1.15em;\n"
			. "\tmargin-right: 0.4em;\n"
			. "\tvertical-align: -0.2em;\n"
			. "\tbackground-color: currentcolor;\n"
			. "\t-webkit-mask-repeat: no-repeat;\n"
			. "\tmask-repeat: no-repeat;\n"
			. "\t-webkit-mask-position: center;\n"
			. "\tmask-position: center;\n"
			. "\t-webkit-mask-size: contain;\n"
			. "\tmask-size: contain;\n"
			. '}';

		$forced = "@media (forced-colors: active) {\n"
			. "\t" . implode( ",\n\t", $selectors ) . " {\n"
			. "\t\tforced-color-adjust: none;\n"
			. "\t\tbackground-color: CanvasText;\n"
			. "\t}\n"
			. '}';

		return self::CSS_BEGIN . "\n" . $base . "\n\n" . implode( "\n\n", $rules ) . "\n\n" . $forced . "\n" . self::CSS_END;
	}

	/**
	 * A standalone SVG for a data URI, percent-encoded where CSS needs it.
	 * `currentColor` inside a standalone image resolves to black, which is
	 * all a mask needs: only the alpha channel is read.
	 *
	 * @param string $name Icon name.
	 */
	private static function dataUriBody( string $name ): string {
		$svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">'
			. self::PATHS[ $name ]
			. '</svg>';

		return strtr(
			str_replace( '"', "'", $svg ),
			array(
				'<' => '%3C',
				'>' => '%3E',
				'#' => '%23',
			)
		);
	}
}
